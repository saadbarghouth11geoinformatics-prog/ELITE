const fs = require('fs')
const path = require('path')
const crypto = require('crypto')

const ROOT_DIR = path.resolve(__dirname, '..')
const PUBLIC_DIR = path.join(ROOT_DIR, 'public')
const OUTPUT_FILE = path.join(ROOT_DIR, 'src', 'data', 'generated', 'publicMediaManifest.ts')
const BREAKFAST_DIR = path.join(PUBLIC_DIR, 'images', 'الفطار')
const IMAGE_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp', '.avif'])
const VIDEO_EXTENSIONS = new Set(['.mp4', '.webm', '.mov', '.m4v'])
const sortOptions = { numeric: true, sensitivity: 'base' }

const walkDirectory = (directoryPath) => {
  if (!fs.existsSync(directoryPath)) return []

  return fs.readdirSync(directoryPath, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(directoryPath, entry.name)

    if (entry.isDirectory()) {
      return walkDirectory(fullPath)
    }

    return entry.isFile() ? [fullPath] : []
  })
}

const toPublicPath = (filePath) => {
  const relativePath = path.relative(PUBLIC_DIR, filePath).split(path.sep).join('/')
  return encodeURI(`/${relativePath}`)
}

const filePriority = (filePath) => {
  const fileName = path.basename(filePath)
  return fileName.includes('(') ? 1 : 0
}

const hashFile = (filePath) =>
  crypto.createHash('sha1').update(fs.readFileSync(filePath)).digest('hex')

const sortFiles = (files) =>
  files.sort(
    (left, right) =>
      filePriority(left) - filePriority(right) || left.localeCompare(right, 'en', sortOptions)
  )

const videoFiles = sortFiles(
  walkDirectory(PUBLIC_DIR).filter((filePath) =>
    VIDEO_EXTENSIONS.has(path.extname(filePath).toLowerCase())
  )
)

const seenHashes = new Set()
const videoPaths = videoFiles
  .filter((filePath) => {
    const fileHash = hashFile(filePath)
    if (seenHashes.has(fileHash)) return false
    seenHashes.add(fileHash)
    return true
  })
  .map(toPublicPath)

const breakfastFiles = sortFiles(walkDirectory(BREAKFAST_DIR))
const breakfastImagePaths = breakfastFiles
  .filter((filePath) => IMAGE_EXTENSIONS.has(path.extname(filePath).toLowerCase()))
  .map(toPublicPath)
const breakfastVideoPaths = breakfastFiles
  .filter((filePath) => VIDEO_EXTENSIONS.has(path.extname(filePath).toLowerCase()))
  .map(toPublicPath)

const output = `// Auto-generated by scripts/generate-public-media-manifest.cjs. Do not edit by hand.

export const allPublicVideoPaths = ${JSON.stringify(videoPaths, null, 2)} as const
export const breakfastImagePaths = ${JSON.stringify(breakfastImagePaths, null, 2)} as const
export const breakfastVideoPaths = ${JSON.stringify(breakfastVideoPaths, null, 2)} as const
`

fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true })
fs.writeFileSync(OUTPUT_FILE, output)

console.log(`Generated public video manifest with ${videoPaths.length} unique items.`)
